// src/tools/gen-catalog.ts — `npm run gen:catalog`: writes docs/CATALOG.md from the catalog data
// (src/catalog.ts) joined with the live registry. Output is deterministic (LF, no timestamps), so
// tests/catalog.spec.ts can compare the committed file byte-for-byte after CRLF normalisation.
import '../districts/index.js'; // registers every challenge
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { CATALOG, DISTRICTS, type Level } from '../catalog.js';
import { allChallenges } from '../core/registry.js';

const LETTER: Readonly<Record<Level, string>> = { acolyte: 'A', templar: 'T', inquisitor: 'I', divine: 'D' };
const cell = (s: string): string => s.replace(/\|/g, '\|');

/** The catalog as Markdown (LF line endings, ends with one newline). */
export function renderCatalog(): string {
  const registered = new Set(allChallenges().map((c) => c.id));
  const total = CATALOG.length;
  const done = CATALOG.filter((r) => registered.has(r.id)).length;
  const out: string[] = [
    '# HVWA challenge catalog',
    '',
    '<!-- Generated by `npm run gen:catalog` from src/catalog.ts and the registry. Do not edit by hand. -->',
    '',
    'Levels: A = Acolyte, T = Templar, I = Inquisitor, D = Divine; "puzzle" rows have no difficulty tiers.',
    'Status: "✅ registered" = the challenge is in the registry; "planned" = catalog row only.',
    '',
    `**Total: ${done}/${total} registered**`,
    '',
    '| District | Registered | Planned |',
    '|---|---|---|',
  ];
  for (const d of DISTRICTS) {
    const rows = CATALOG.filter((r) => r.district.key === d.key);
    const n = rows.filter((r) => registered.has(r.id)).length;
    out.push(`| ${d.name} | ${n} | ${rows.length - n} |`);
  }
  for (const d of DISTRICTS) {
    const rows = CATALOG.filter((r) => r.district.key === d.key);
    const n = rows.filter((r) => registered.has(r.id)).length;
    out.push('', `## ${d.name}`, '', `${n}/${rows.length} registered`, '',
      '| ID | Title | Standard | Levels | Phase | Status |', '|---|---|---|---|---|---|');
    for (const r of rows) {
      const levels = r.levels.length === 0 ? 'puzzle' : r.levels.map((l) => LETTER[l]).join(' ');
      out.push(`| ${r.id} | ${cell(r.title)} | ${cell(r.standard)} | ${levels} | ${r.phase} | ${registered.has(r.id) ? '✅ registered' : 'planned'} |`);
    }
  }
  return out.join('\n') + '\n';
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const file = join(dirname(fileURLToPath(import.meta.url)), '..', '..', 'docs', 'CATALOG.md');
  writeFileSync(file, renderCatalog());
  console.log(`gen:catalog wrote ${file}`);
}
